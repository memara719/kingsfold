LINE = 11
_cache = {}


def width(s):
    w = 0
    for ch in s:
        w += len(GLYPHS.get(ch, GLYPHS['?'])[0]) + 1
    return max(0, w - 1)


def _render(s, color, shadow):
    key = (s, color, shadow)
    surf = _cache.get(key)
    if surf:
        return surf
    if len(_cache) > 1500:
        _cache.clear()
    surf = pygame.Surface((max(1, width(s) + 1), 10), pygame.SRCALPHA)
    for col, off in ((shadow, 1), (color, 0)):
        if col is None:
            continue
        x = off
        for ch in s:
            g = GLYPHS.get(ch, GLYPHS['?'])
            for r, row in enumerate(g):
                for i, c in enumerate(row):
                    if c == '#':
                        surf.fill(col, (x + i, r + off, 1, 1))
            x += len(g[0]) + 1
    _cache[key] = surf
    return surf


def text(dst, s, x, y, color=(255, 255, 255), shadow=(16, 16, 48), align='left', scale=1):
    """Draw text with the drop shadow every SNES menu had. Returns its width."""
    s = str(s)
    w = width(s) * scale
    if align == 'center':
        x = round(x - w / 2)
    elif align == 'right':
        x = x - w
    surf = _render(s, tuple(color), tuple(shadow) if shadow else None)
    if scale != 1:
        surf = pygame.transform.scale(surf, (surf.get_width() * scale, surf.get_height() * scale))
    dst.blit(surf, (x, y))
    return w


def fit(s, w):
    s = str(s)
    if width(s) <= w:
        return s
    while len(s) > 1 and width(s + '..') > w:
        s = s[:-1]
    return s + '..'


def wrap(s, w):
    out = []
    for para in str(s).split('\n'):
        line = ''
        for word in para.split(' '):
            nxt = line + ' ' + word if line else word
            if width(nxt) > w and line:
                out.append(line)
                line = word
            else:
                line = nxt
        out.append(line)
    return out
