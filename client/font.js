G['’'] = G["'"];

export const LINE = 11;

export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += (G[ch] || G['?'])[0].length + 1;
  return Math.max(0, w - 1);
}

function glyphs(c, str, x, y, color) {
  c.fillStyle = color;
  let cx = x;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    for (let r = 0; r < g.length; r++) {
      const row = g[r];
      for (let i = 0; i < row.length; i++) if (row[i] === '#') c.fillRect(cx + i, y + r, 1, 1);
    }
    cx += g[0].length + 1;
  }
  return cx - x - 1;
}

const cache = new Map();

function render(str, color, shadow) {
  const key = str + '\u0000' + color + '\u0000' + shadow;
  let cv = cache.get(key);
  if (cv) return cv;
  if (cache.size > 900) cache.clear();
  cv = document.createElement('canvas');
  cv.width = Math.max(1, textWidth(str) + 1); cv.height = 10;
  const c = cv.getContext('2d');
  if (shadow) glyphs(c, str, 1, 1, shadow);
  glyphs(c, str, 0, 0, color);
  cache.set(key, cv);
  return cv;
}

// Text with the drop shadow every SNES menu had. align: 'left' | 'center' | 'right'.
export function text(c, str, x, y, color = '#ffffff', { shadow = '#101030', align = 'left', scale = 1 } = {}) {
  str = String(str);
  const w = textWidth(str) * scale;
  if (align === 'center') x = Math.round(x - w / 2);
  if (align === 'right') x = x - w;
  const cv = render(str, color, shadow || '');
  c.drawImage(cv, x, y, cv.width * scale, cv.height * scale);
  return w;
}

// Cut a string to fit, ending in '..' when it had to be shortened.
export function fit(str, width) {
  str = String(str);
  if (textWidth(str) <= width) return str;
  while (str.length > 1 && textWidth(str + '..') > width) str = str.slice(0, -1);
  return str + '..';
}

export function wrap(str, width) {
  const lines = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? line + ' ' + word : word;
      if (textWidth(next) > width && line) { lines.push(line); line = word; } else line = next;
    }
    lines.push(line);
  }
  return lines;
}

export function paragraph(c, str, x, y, width, color, opts) {
  const lines = wrap(str, width);
  lines.forEach((l, i) => text(c, l, x, y + i * LINE, color, opts));
  return lines.length * LINE;
}
